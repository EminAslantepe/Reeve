/// Claude kimliği ve oturum durumu ayrı ayrı okunabilir kalır.
struct SessionLeadingIcon: View {
    let session: Session

    var body: some View {
        Group {
            if session.kind == .claude {
                ClaudeMark().fill(Theme.primary)
                    .frame(width: 18, height: 18)
                    .overlay(alignment: .bottomTrailing) {
                        StatusDot(status: session.status, origin: session.origin)
                            .scaleEffect(0.55)
                            .frame(width: 6, height: 6)
                            .background(Theme.sidebar, in: Circle())
                            .offset(x: 3, y: 3)
                    }
                    .accessibilityLabel("Claude")
            } else {
                StatusDot(status: session.status, origin: session.origin)
            }
        }
        .frame(width: 18, height: 18)
    }
}
